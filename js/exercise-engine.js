        type: "text", class: "field ex-para-input" + (r ? (r.correct ? " is-ok" : " is-bad") : "") + (r && r.correct && run.mode === "learn" ? " ex-hl" : ""),
        id: id, value: st.texts[i] || "", disabled: done, "data-fk": k === 0 ? "first" : "cell-" + i,
