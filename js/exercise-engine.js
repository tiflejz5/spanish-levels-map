  /** The model answer as text. */
  function modelAnswer(item) {
    if (item.type === "multiple-choice") return item.options[item.correct];
    if (item.type === "reorder") return item.answers[0];
    if (item.type === "short-answer") return String(item.prompt).replace("___", item.accepted[0]);
    if (item.type === "gap-fill") return gapText(item, function (i) { return item.gaps[i].accepted[0]; });
    if (item.type === "match") return item.pairs.map(function (p) { return p[0] + " – " + p[1]; }).join("; ");
    if (item.type === "transformation") return [item.before, item.answers[0], item.after].filter(Boolean).join(" ");
    if (item.type === "translate") return item.accepted[0];
    if (item.type === "dictation") return item.text;
    if (item.type === "paradigm") return paradigmText(item, function (c) { return c.accepted[0]; }, "; ");
    if (item.noError) return "The sentence is correct – there is no mistake in it.";
    const t = item.tokens.slice();
    const fix = item.fixes[0];
    t.splice(item.errorRange[0], item.errorRange[1] - item.errorRange[0] + 1, fix);
    return t.filter(function (w) { return w !== ""; }).join(" ");
  }

  /** paradigm as text: "lemma – label: form; label: …" (sep) or one cell per line; fill(cell, index) gives the form. */
  function paradigmText(item, fill, sep) {
    return item.lemma + (sep ? " – " : "\n") + item.cells.map(function (c, i) { return c.label + ": " + fill(c, i); }).join(sep || "\n");
  }

  /** gap-fill text with the {{n}} gaps filled by fill(index). */
  function gapText(item, fill) {
    return String(item.text).replace(/\{\{(\d+)\}\}/g, function (m, n) { return fill(Number(n) - 1); });
  }

  /** Match pairs as text: only the wrong ones (onlyWrong) or all. */
  function matchText(p, onlyWrong) {
    return p.item.pairs.map(function (pair, i) {
      if (onlyWrong && p.res && p.res.pairs && p.res.pairs[i]) return null;
      const id = p.st.pairs[i];
      return pair[0] + " – " + (id !== undefined ? rightById(p, id).text : "(no pair)");
    }).filter(Boolean).join("; ");
  }

  /** The user's answer as text (for the list of mistakes). */
  function userAnswer(p) {
    const st = p.st, item = p.item;
    if (item.type === "multiple-choice") return st.chosen === null ? "" : p.choice.options[st.chosen].text;
    if (item.type === "reorder") return st.line.map(function (t) { return t.text; }).join(" ");
    if (item.type === "short-answer") return st.text;
    if (item.type === "gap-fill") return st.texts.some(function (t) { return t && t.trim(); }) ? gapText(item, function (i) { return "[" + ((st.texts[i] || "").trim() || "…") + "]"; }) : "";
    if (item.type === "match") return Object.keys(st.pairs).length ? matchText(p, false) : "";
    if (item.type === "paradigm") {
      const open = X().paradigmCells(item);
      return open.some(function (i) { return st.texts[i] && st.texts[i].trim(); })
        ? open.map(function (i) { return item.cells[i].label + ": " + ((st.texts[i] || "").trim() || "…"); }).join("; ") : "";
    }
    if (item.type === "dictation" && p.res && p.res.skipped) return "Skipped (no voice)";
    if (item.type === "transformation" || item.type === "translate" || item.type === "dictation") return st.text.trim();
    if (st.noError) return "No mistake";
    if (!st.range) return "";
    return "“" + item.tokens.slice(st.range[0], st.range[1] + 1).join(" ") + "” → “" + st.fix + "”";
  }

  /** The item in one sentence (the list of mistakes on the result screen). */
  function itemSummary(item) {
    if (item.type === "multiple-choice") return String(item.prompt || "").replace(/\n/g, " / ");
    if (item.type === "reorder") return item.context ? "Put in order: " + item.context : "Put the sentence in order";
    if (item.type === "find-error") return item.tokens.join(" ");
    if (item.type === "gap-fill") return (item.context ? item.context + " → " : "") + gapText(item, function () { return "___"; });
    if (item.type === "match") return item.prompt || "Match the pairs";
    if (item.type === "transformation") return item.source + " (" + String(item.keyword).toUpperCase() + ") → " + [item.before, "___", item.after].filter(Boolean).join(" ");
    if (item.type === "translate") return "Translate: " + item.source;
    if (item.type === "dictation") return "Dictation";
    if (item.type === "paradigm") return "Fill the table: " + item.lemma + (item.prompt ? " – " + item.prompt : "");
    return (item.context ? item.context + " → " : "") + item.prompt;
  }

  /** C4: the sentence with the user's answer, the key word highlighted. */
  function keywordLine(item, answer) {
    const full = [item.before, answer, item.after].filter(function (s) { return s && String(s).trim(); }).join(" ");
    const kw = String(item.keyword || "");
    const esc = kw.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
    // Unicode word edges (\b does not see letters with diacritics as letters)

    const parts = kw ? full.split(new RegExp("((?<![\\p{L}\\p{N}])" + esc + "(?![\\p{L}\\p{N}]))", "iu")) : [full];
    return el("p", { class: "ex-hl-line", lang: LM.APP.targetLang }, parts.map(function (s, i) {
      return i % 2 ? el("span", { class: "ex-hl", text: s }) : s;
    }));
  }

  /** translate / dictation: the accepted sentence number k (as written in the item). */
  function sentenceModel(item, k) {
    const list = item.type === "translate" ? item.accepted : [item.text].concat(item.accepted || []);
    return list[k || 0] || list[0] || "";
  }

  /** "Almost. Check the accents: <closest>" (LM.exLogic.nearText, the answer in bold); lenient = counted as right, the reminder stays. */
  function nearLine(near, closest, lenient, prefix) {
    return el("p", { class: "ex-spelling ex-near is-" + near }, [
      LM.icon("triangle-alert", { size: 14 }), " ",
      prefix + X().nearText(near),
      el("strong", { lang: LM.APP.targetLang, text: closest }),
      lenient ? el("span", { class: "ex-near-note", text: " (counted as right: you accept answers without accents)" }) : null
    ]);
  }

  function feedback(p) {
    const item = p.item, res = p.res;
    const lines = [];
    let verdict = res.correct ? "Right!" : "Not quite.";
    if (item.type === "find-error" && !res.correct) {
      if (p.st.noError) verdict = "There is a mistake in this sentence.";
      else if (item.noError) verdict = "This sentence is correct.";
      else if (!res.rangeOk) verdict = "The mistake was somewhere else: “" + item.tokens.slice(item.errorRange[0], item.errorRange[1] + 1).join(" ") + "”.";
      else verdict = "Right place, but the fix does not fit.";
    }
    if (item.type === "reorder" && !res.correct && res.diffAt >= 0) verdict = "Not quite – the order differs from word " + (res.diffAt + 1) + " on.";
    if (!res.correct && res.points > 0) verdict = "Partly right.";
    if (!res.correct && res.near && (item.type === "translate" || item.type === "dictation")) verdict = "Almost.";
    if (res.skipped) verdict = "Skipped – without a voice this item does not count in the result.";
    lines.push(el("p", { class: "lt-verdict" }, [
      el("span", { class: "c1-mark " + (res.correct ? "is-ok" : "is-bad"), "aria-hidden": "true" }, LM.icon(res.correct ? "check" : res.skipped ? "arrow-right" : "x", { size: 14 })),
      el("strong", { text: verdict }),
      res.max > 1 ? el("span", { class: "ex-points num", text: " " + res.points + " / " + res.max + " points" }) : null
    ]));
    // Near misses (spec 05 §2): accents / ending / typo with the closest right answer; also after a lenient "right"
    if (item.type === "gap-fill") {
      res.gaps.forEach(function (g, i) { if (g.near) lines.push(nearLine(g.near, g.closest, g.lenient, "Gap " + (i + 1) + ": ")); });
    } else if (item.type === "paradigm") {
      res.cells.forEach(function (c, i) { if (c && c.near) lines.push(nearLine(c.near, c.closest, c.lenient, item.cells[i].label + ": ")); });
    } else if (res.near && !res.skipped) {
      const closest = typeof res.closest === "number" ? sentenceModel(item, res.closest) : res.closest;
      lines.push(nearLine(res.near, closest, res.lenient, ""));
    }
    if (item.type === "transformation") {
      if (res.msg) lines.push(el("p", { class: "ex-spelling", text: res.msg }));
      if (keyOn(p)) lines.push(keywordLine(item, p.st.text));
      if (item.parts && !res.msg && !res.correct) {
        lines.push(el("p", { class: "c1-parts" }, res.parts.map(function (ok, k) {
          return el("span", { class: "c1-part " + (ok ? "is-ok" : "is-bad") }, [LM.icon(ok ? "check" : "x", { size: 14 }), " Part " + (k + 1) + ": " + (ok ? "right" : "wrong")]);
        })));
      }
    }
    const sentence = item.type === "translate" || item.type === "dictation";
    if (sentence && !res.correct && res.diff) lines.push(diffView(res.diff));
    // "Right answer: …" after a mistake for every type (also Match pairs: pairs as text under the list)
    if (!res.correct || item.type === "reorder" || item.type === "find-error") {
      const model = sentence && !res.skipped ? (item.type === "translate" ? item.accepted : [item.text].concat(item.accepted || []))[res.closest || 0] : modelAnswer(item);
      lines.push(el("p", { class: "journal-row is-right" }, [el("span", { class: "review-label", text: res.skipped ? "Text: " : "Right answer: " }), el("strong", { lang: LM.APP.targetLang, text: model })]));
    }
    if (p.reviewed) lines.push(el("p", { class: "ex-journal-note is-ok" }, [LM.icon("check", { size: 14 }), " Mistake log review passed"]));
    if (p.journalLimit) lines.push(el("p", { class: "ex-journal-note", text: "The log is full for today – this mistake is saved only in the stats." }));
    if (item.explanation) lines.push(el("p", { text: item.explanation }));
    if (item.trap) {
      lines.push(el("div", { class: "ex-trap" }, [
        el("span", { class: "ex-trap-icon", "aria-hidden": "true" }, LM.icon("triangle-alert", { size: 16 })),
        el("p", null, [el("strong", { text: "Trap: " }), item.trap])
      ]));
    }
    return lines;
  }

