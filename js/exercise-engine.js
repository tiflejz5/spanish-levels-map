  function parseRoute(hash) {
    const fin = /^#\/([abcABC][12])\/test\/?$/.exec(hash || "");
    if (fin) return { kind: "final", id: fin[1].toUpperCase() }; // level final test (js/final.js)
    const weak =/^#\/practice\/weak(?:\/([a-z0-9-]+))?\/?$/.exec(hash || "");
    if (weak) return { kind: "weak", id: weak[1] || "" }; // weak-spot practice (all or one topic)
    const hub = /^#\/practice(\/mixes)?\/?$/.exec(hash || "");
    if (hub) return { kind: "hub", section: hub[1] ? "mixes" : null }; // Practice (js/practice-hub.js)
    let m = /^#\/practice\/(set|mix)\/([a-z0-9-]+)\/?$/.exec(hash || "");
    if (m) return { kind: m[1] === "set" ? "set" : "mix", id: m[2] };
    if (/^#\/practice\/session\/?$/.test(hash || "")) return { kind: "custom" };
    return null;
  }

  function hrefOf(route) {
    if (route.kind === "hub") return BASE;
    if (route.kind === "set") return BASE + "/set/" + route.id;
    if (route.kind === "mix") return BASE + "/mix/" + route.id;
    if (route.kind === "weak") return BASE + "/weak" + (route.id ? "/" + route.id : "");
    if (route.kind === "final") return "#/" + route.id.toLowerCase() + "/test";
    return BASE + "/session";
  }

  // Current session (in the tab's memory; closing the tab = no partial result saved)
  let run = null;

  /** An item prepared for the session: random order of options / words and the answer state. */
  function prepare(item) {
    const p = { item: item, st: { chosen: null, line: [], range: null, anchor: null, fix: "", text: "", noError: false, texts: [], pairs: {}, sel: null, plays: 0, hint: false }, res: null };
    if (item.type === "multiple-choice") p.choice = X().prepareChoice(item);
    if (item.type === "reorder") p.tokens = X().reorderTokens(item);
    if (item.type === "match") p.right = X().prepareMatch(item);
    return p;
  }

  /**
   * New session. cfg: { key, title, intro, items, mode, topic, saveId, isMix, routeHash }
   * key — what is being solved (e.g. "set:a2-…"), saveId — the id the result is saved under.
   */
  function newRun(cfg) {
    const profile = LM.app.getActiveProfile();
    run = {
      key: cfg.key, title: cfg.title, intro: cfg.intro || "", topic: cfg.topic || null,
      saveId: cfg.saveId || null, isMix: !!cfg.isMix, isWeak: !!cfg.isWeak, repick: cfg.repick || null,
      passage: cfg.passage || null, exam: cfg.exam || null,
      // Level final test (js/final.js): its own result saving and result screen, back to the level
      hooks: cfg.hooks || null, back: cfg.back || null, final: null,
      // Shared recording of a set (listening parts): one play counter for all items
      script: cfg.script || null, listen: { plays: 0, readMode: false },
      profileId: profile ? profile.id : null,
      phase: "intro",
      mode: cfg.mode === "exam" ? "exam" : "learn",
      i: 0,
      retry: !!cfg.retry,
      saved: null,
      score: 0,
      journal: { added: [], reviewed: 0, limit: false } // automatic mistake log in this session
    };
    run.source = cfg.items.slice();
    run.items = cfg.items.map(prepare);
    return run;
  }

  function begin() {
    run.phase = "item";
    run.i = 0;
    render();
    focusLater("[data-fk='first']");
  }

  /** The answer in the LM.exLogic.evaluate format. */
  function answerOf(p) {
    const st = p.st;
    if (p.item.type === "multiple-choice") return { chosen: st.chosen === null ? null : p.choice.options[st.chosen].original };
    if (p.item.type === "reorder") return { words: st.line.map(function (t) { return t.text; }) };
    if (p.item.type === "find-error") return st.noError ? { noError: true } : { range: st.range, fix: st.fix };
    if (p.item.type === "gap-fill" || p.item.type === "paradigm") return { texts: st.texts };
    if (p.item.type === "match") {
      const pairs = {};
      Object.keys(st.pairs).forEach(function (i) { pairs[i] = rightById(p, st.pairs[i]).text; });
      return { pairs: pairs };
    }
    // Dictation without a voice: skipped (counts neither in the result nor in the stats)
    if (p.item.type === "dictation" && noVoice()) return { skipped: true };
    return { text: st.text };
  }

  function rightById(p, id) { return p.right.find(function (r) { return r.id === id; }) || { id: id, text: "" }; }

  const NEED_ANSWER = {
    "multiple-choice": "Choose an answer first.",
    "reorder": "Build the sentence from the words below first.",
    "find-error": "Select the word with the mistake first, or choose “No mistake”.",
    "short-answer": "Type your answer in the gap first.",
    "gap-fill": "Type your answers in the gaps first.",
    "match": "Match at least one pair first.",
    "transformation": "Complete the sentence first.",
    "translate": "Type your translation first.",
    "dictation": "Listen to the recording and type what you hear first.",
    "paradigm": "Fill in the table first."
  };

  /** "Check" (Learn) or "Next" (Exam). */
  function check() {
    const p = run.items[run.i];
    if (p.res) return next();
    const res = X().evaluate(p.item, answerOf(p), { lenientAccents: lenientAccents() });
    if (run.mode === "learn" && !res.answered) {
      const box = document.querySelector(".ex-status");
      if (box) { box.textContent = NEED_ANSWER[p.item.type]; box.classList.add("is-hint"); }
      return;
    }
    p.res = res;
    stopSpeaking();
    // Skipped dictation (no voice): not in the attempts log, the stats or the mistake log
    if (!res.skipped) {
      logAttempt(p);
      if (res.correct) creditReview(p);
      else if (run.mode !== "exam") toJournal(p, !run.isMix && !run.isWeak); // Exam: only after the session ends
    }
    if (run.mode === "exam") return next();
    render();
    animate(res.correct);
    focusLater(".ex-next");
  }

  /** Preference "accept answers without accents" of the active profile (spec 06 E4); off without a profile. */
  function lenientAccents() {
    try { return !!(pd() && pd().prefs().lenientAccents); } catch (e) { return false; }
  }

  /** Mode in the attempts log: learn / exam (set), mix (mixed), weak (weak spots). */
  function attemptMode() { return run.isWeak ? "weak" : run.isMix ? "mix" : run.mode; }

  /** Every answer goes into the attempts log (slm.attempts), also when the session is interrupted. */
  function logAttempt(p) {
    pd().addAttempt({
      itemId: p.item.id, setId: p.item.setId || null, topic: p.item.topic, level: p.item.level,
      // Listening read from the transcript (no voice) — marked, left out of the listening stats
      type: p.item.type, tags: p.st.readMode ? (p.item.tags || []).concat("read") : p.item.tags,
      correct: !!p.res.correct, mode: attemptMode(), answer: userAnswer(p), lenient: p.res.lenient === true ? true : undefined,
      // Items worth several points: points as well (optional fields; the stats count by correct)
      points: p.res.max > 1 ? p.res.points : undefined, max: p.res.max > 1 ? p.res.max : undefined
    });
  }

  // ---------- Automatic mistake log (spec 03, point 2) ----------

  function journalCategory(topic) {
    return pd().journalCategoryOf(topic);
  }

  /** Text of the mistake log entry for an item (context by type, model answer, rule with the trap). */
  function journalFields(p) {
    const item = p.item;
    let context;
    if (item.type === "multiple-choice") context = String(item.prompt || "") + "\n" + item.options.join(" / ");
    else if (item.type === "reorder") context = (item.context ? item.context + " – " : "") + "Put the words in order: " + p.tokens.map(function (t) { return t.text; }).join(" / ");
    else if (item.type === "find-error") context = item.tokens.join(" ");
    else if (item.type === "gap-fill") {
      // hints next to the gaps (e.g. the base form in brackets) written under the sentence — without them the entry does not say what the gap should be
      const hints = item.gaps.map(function (g, i) { return g.hint ? "Gap " + (i + 1) + ": " + g.hint : null; }).filter(Boolean);
      context = (item.context ? item.context + "\n" : "") + gapText(item, function () { return "___"; }) + (hints.length ? "\n" + hints.join("\n") : "");
    }
    else if (item.type === "match") context = (item.prompt || "Match the pairs") + "\n" + item.pairs.map(function (x) { return x[0]; }).join(" / ") + "\n" + item.pairs.map(function (x) { return x[1]; }).join(" / ");
    else if (item.type === "transformation") context = item.source + "\n" + String(item.keyword).toUpperCase() + "\n" + [item.before, "___", item.after].filter(Boolean).join(" ");
    else if (item.type === "translate") context = "Translate: " + item.source;
    else if (item.type === "dictation") context = "Dictation: " + item.text;
    else if (item.type === "paradigm") context = (item.prompt ? item.prompt + "\n" : "") + paradigmText(item, function (c) { return c.given ? c.accepted[0] : "___"; });
    else context = (item.context ? item.context + "\n" : "") + item.prompt;
    const rule = (item.explanation || "") + (item.trap ? " Trap: " + item.trap : "");
    // Match pairs: only the wrong pairs go into the log (mine and the right ones)
    const wrongPairs = item.type === "match" && p.res && p.res.pairs ? item.pairs.filter(function (_, i) { return !p.res.pairs[i]; }) : null;
    return {
      context: context,
      myAnswer: (wrongPairs ? matchText(p, true) : userAnswer(p)) || "(no answer)",
      correct: wrongPairs ? wrongPairs.map(function (x) { return x[0] + " – " + x[1]; }).join("; ") : modelAnswer(item),
      rule: rule.trim(),
      source: "Set: " + run.title,
      category: journalCategory(item.topic),
      itemId: item.topic || ""
    };
  }

  /** A wrong answer → an entry in the mistake log (no duplicates); a toast with "Undo" only in a normal set in Learn mode. */
  function toJournal(p, withToast) {
    if (run.hooks && run.hooks.noJournal) return; // an item from a log entry in a review session: its "My mistakes" card rates it
    const r = pd().recordWrong(p.item.id, journalFields(p));
    if (!r) return;
    if (r.action === "limit") { run.journal.limit = true; p.journalLimit = true; return; }
    const rec = { undo: r.undo, action: r.action };
    run.journal.added.push(rec);
    p.journal = r.action;
    if (LM.cards && r.entry) LM.cards.autoAddFromJournal(r.entry); // the "add mistakes to flashcards automatically" option (off by default)
    if (LM.app.refreshLearning) LM.app.refreshLearning();
    if (!withToast) return;
    const text = r.action === "create" ? "Added to the mistake log"
      : r.action === "reopen" ? "A mastered mistake is back in the log – review tomorrow"
        : "This mistake is already in the log – review tomorrow";
    LM.ui.toast({
      text: text, icon: "notebook-pen",
      action: { label: "Undo", onClick: function () {
        pd().undoAuto(rec.undo);
        run.journal.added = run.journal.added.filter(function (x) { return x !== rec; });
        p.journal = null;
        if (LM.app.refreshLearning) LM.app.refreshLearning();
        LM.ui.toast({ text: "Undone – the entry did not go into the log.", duration: 3000 });
      } }
    });
  }

  /** A right answer to an item with an entry due today / overdue = a passed review. */
  function creditReview(p) {
    if (run.hooks && run.hooks.noJournal) return;
    const r = pd().recordCorrect(p.item.id);
    if (!r) return;
    p.reviewed = true;
    run.journal.reviewed++;
    if (LM.app.refreshLearning) LM.app.refreshLearning();
  }

  function next() {
    // The shared recording keeps playing on the next item; it ends with the set
    if (!run.script || run.i >= run.items.length - 1) stopSpeaking();
    if (run.i < run.items.length - 1) {
      run.i++;
      render();
      U.setScroll(0);
      focusLater("[data-fk='first']");
    } else {
      finish();
    }
  }

  function finish() {
    run.phase = "done";
    // Exam: mistakes go into the log only after the session ends
    if (run.mode === "exam") run.items.forEach(function (p) { if (isWrong(p)) toJournal(p, false); });
    // Result in points (an item can give several points); a set of old types: point = right item
    const s = X().sessionScore(run.items);
    run.score = s.score;
    run.total = s.total;
    if (run.hooks && run.hooks.finish) run.final = run.hooks.finish(run, s); // final test: its own saving (slm.finals)
    else if (!run.retry && run.saveId) run.saved = pd().saveSetScore(run.saveId, s.score, s.total);
    run.suggest = knownSuggestion();
    if (run.isMix) pd().setLastMix(run.items.map(function (p) { return p.item.id; }));
    LM.markActivity(); // a finished session = a study day
    if (LM.app.refreshLearning) LM.app.refreshLearning();
    if (run.hooks && run.hooks.afterFinish) run.hooks.afterFinish(run); // e.g. congratulations on a passed level
    render();
    U.setScroll(0);
    focusLater(".ex-result .btn-primary, .ex-result .btn");
  }

  /** An item without full points (a skipped dictation does not count). */
  function isWrong(p) { return !(p.res && (p.res.correct || p.res.skipped)); }

  /** A "pop" or a shake of the card (CSS; no animation with reduced motion). */
  function animate(ok) {
    const card = document.querySelector(".ex-card");
    if (!card) return;
    card.classList.remove("is-pop", "is-shake");
    void card.offsetWidth;
    card.classList.add(ok ? "is-pop" : "is-shake");
  }

  let focusTimer = null;
  /** Focus after a redraw; a newer call replaces a pending one (fast keys do not jump focus back). */
  function focusLater(selector) {
    clearTimeout(focusTimer);
    focusTimer = setTimeout(function () {
      const n = document.querySelector(selector);
      if (n) n.focus({ preventScroll: true });
    }, 0);
  }

  /** Redraws the current item, keeping scroll and focus (data-fk). */
  function repaint(focusKey) {
    const scroll = U.getScroll();
    render();
    U.setScroll(scroll);
    if (focusKey) focusLater("[data-fk='" + focusKey + "']");
  }

