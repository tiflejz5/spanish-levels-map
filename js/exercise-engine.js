  /** Set card: title, number of items, types, best and last result, "Start". */
  function setCard(meta) {
    const score = pd().setScore(meta.id);
    // A set with items worth several points: also the maximum points (results are in points)
    const points = meta.points && meta.points !== meta.count ? " · " + meta.points + " points" : "";
    return el("article", { class: "card ex-set-card lvl-" + (meta.level || "A1") }, [
      el("h3", { class: "ex-set-title", text: meta.title }),
      el("p", { class: "ex-set-meta", text: LM.plural(meta.count, "item") + points + " · " + typesText(meta.types) }),
      el("p", { class: "ex-set-score" + (score ? "" : " is-empty") }, score
        ? [el("span", null, ["Best: ", el("strong", { class: "num", text: scoreText(score.best) })]), el("span", null, ["Last: ", el("span", { class: "num", text: scoreText(score.last) })])]
        : "Not done yet"),
      el("a", { class: "btn btn-primary btn-small", href: BASE + "/set/" + meta.id, "aria-label": (score ? "Start again: " : "Start: ") + meta.title }, LM.ui.withIcon("play", score ? "Start again" : "Start"))
    ]);
  }

  /**
   * Set labels for the level page (S4): Promise<{ <topic id>: { score, total, high, text } }> — only topics with a done set.
   * Called after the index has loaded, so the list draws at once and the labels come a moment later.
   */
  function setLabels(topicIds) {
    return loadIndex().then(function (index) {
      const out = {};
      topicIds.forEach(function (t) {
        const bests = (index.topics[t] || []).map(function (id) { const sc = pd().setScore(id); return sc ? sc.best : null; });
        const label = X().bestSetLabel(bests);
        if (label) out[t] = label;
      });
      return out;
    });
  }

  /**
   * Section at the end of a topic page. Returns the element at once (empty and hidden);
   * fills it after the index loads, when the topic has sets or a card in the lab.
   */
  function topicSection(topicId) {
    const box = el("section", { class: "ex-topic", "aria-labelledby": "ex-topic-title", hidden: true });
    loadIndex().then(function (index) {
      const sets = (index.topics[topicId] || []).map(function (id) { return index.sets[id]; }).filter(Boolean);
      const tense = index.tenseByTopic && index.tenseByTopic[topicId];
      if (!sets.length && !tense) return;
      box.replaceChildren();
      U.appendChildren(box, [
        el("h2", { class: "ex-topic-title", id: "ex-topic-title" }, [
          el("span", { class: "callout-icon", "aria-hidden": "true" }, LM.icon("list-checks", { size: 20 })),
          "Check yourself"
        ]),
        sets.length ? el("div", { class: "ex-set-grid" }, sets.map(setCard)) : null,
        tense ? el("p", { class: "ex-topic-lab" }, el("a", { class: "btn btn-secondary", href: tense.route || "#/lab/" + tense.id }, LM.ui.withIcon("flask-conical", (tense.kind === "contrast" ? "Contrast card in the Lab: " : "See it on the timeline: ") + tense.name))) : null
      ]);
      box.hidden = false;
    });
    return box;
  }

