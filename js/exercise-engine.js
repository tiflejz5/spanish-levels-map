  /** Summary of the mistake log: "3 mistakes added to the log" + See / Undo all. */
  function journalSummary() {
    const j = run.journal;
    const created = j.added.filter(function (x) { return x.action === "create"; }).length;
    const updated = j.added.length - created;
    const lines = [];
    if (created) lines.push(plural(created, "mistake") + " added to the log.");
    if (updated) lines.push(plural(updated, "mistake was", "mistakes were") + " already in the log – " + (updated === 1 ? "its review" : "their reviews") + " tomorrow.");
    if (j.reviewed) lines.push("Mistake log reviews passed: " + j.reviewed + ".");
    if (j.limit) lines.push("The log is full for today – more mistakes are saved only in the stats.");
    const off = !pd().prefs().autoJournal && run.items.some(function (p) { return p.res && isWrong(p); });
    if (!lines.length && !off) return null;
    const box = el("div", { class: "ex-journal" }, [
      el("span", { class: "ex-journal-icon", "aria-hidden": "true" }, LM.icon("notebook-pen", { size: 18 })),
      el("div", { class: "ex-journal-body" }, [
        lines.length ? el("p", { text: lines.join(" ") }) : null,
        off ? el("p", { class: "tool-note", text: "Adding mistakes to the log automatically is turned off (profile menu → Learning settings)." }) : null,
        j.added.length ? el("p", { class: "ex-journal-actions" }, [
          el("a", { class: "btn btn-secondary btn-small", href: "#/review/mistakes" }, "See them"),
          el("button", { type: "button", class: "btn btn-link btn-small", onclick: function () {
            j.added.slice().reverse().forEach(function (x) { pd().undoAuto(x.undo); });
            j.added = [];
            run.items.forEach(function (p) { p.journal = null; });
            if (LM.app.refreshLearning) LM.app.refreshLearning();
            repaint(null);
            LM.ui.toast({ text: "Undone – the mistakes of this session did not go into the log.", duration: 3000 });
          } }, LM.ui.withIcon("rotate-ccw", "Undo all"))
        ]) : null
      ])
    ]);
    return box;
  }

  /** Accuracy per topic in a mixed session: "Best: …, to review: …". */
  function topicBreakdown() {
    const per = {};
    run.items.forEach(function (p) {
      if (p.res && p.res.skipped) return;
      const k = p.item.topic || "";
      per[k] = per[k] || { ok: 0, n: 0 };
      per[k].n++;
      if (p.res && p.res.correct) per[k].ok++;
    });
    const rows = Object.keys(per).map(function (k) {
      const info = topicInfo(k);
      return { name: info ? info.title : k, href: info ? info.href : null, ok: per[k].ok, n: per[k].n, r: per[k].ok / per[k].n };
    }).sort(function (a, b) { return b.r - a.r || a.n - b.n; }); // last = weakest (tie: more items)
    if (!rows.length) return null;
    const best = rows[0], worst = rows[rows.length - 1];
    return el("div", { class: "ex-breakdown" }, [
      el("p", null, [el("span", { class: "review-label", text: "Best: " }), el("strong", { text: best.name }), " (" + best.ok + "/" + best.n + ")"]),
      worst !== best && worst.r < 1 ? el("p", null, [el("span", { class: "review-label", text: "To review: " }),
        worst.href ? el("a", { href: worst.href }, worst.name) : el("strong", { text: worst.name }), " (" + worst.ok + "/" + worst.n + ")"]) : null,
      el("ul", { class: "ex-breakdown-list" }, rows.map(function (r) {
        return el("li", null, [el("span", { text: r.name }), el("span", { class: "num", text: r.ok + "/" + r.n })]);
      }))
    ]);
  }

  /** The first ready mix that contains the topic (the "Next: a mixed set" link). */
  function mixFor(topic) {
    const index = LM.SETS_INDEX;
    if (!index || !topic) return null;
    return index.mixes.find(function (m) { return m.topics.indexOf(topic) !== -1; }) || null;
  }

  function retryWrong() {
    const wrong = run.items.filter(isWrong).map(function (p) { return p.item; });
    newRun(Object.assign({}, run, { items: wrong, retry: true }));
    begin();
  }

  function redo() {
    if (run.isMix && run.repick) return run.repick();
    const cfg = Object.assign({}, run, { items: X().shuffle(run.source), retry: false });
    newRun(cfg);
    begin();
  }

