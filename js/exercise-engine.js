  /** Prepares the session for a route (redraws after the data has loaded). */
  function ensureRun(route) {
    const key = route.kind + ":" + (route.id || "");
    const profile = LM.app.getActiveProfile();
    if (run && run.key === key && run.profileId === (profile && profile.id)) return true;
    if (route.kind === "custom") return false;
    if (route.kind === "weak") { buildWeak(route, key, hrefOf(route)); return null; }
    const hash = hrefOf(route);
    if (route.kind === "set") {
      loadSets([route.id]).then(function (sets) {
        if (location.hash !== hash) return;
        if (!sets.length) { run = { key: key, missing: true, profileId: profile && profile.id }; return render(); }
        const s = sets[0];
        const meta = (LM.SETS_INDEX && LM.SETS_INDEX.sets[s.id]) || {};
        newRun({ key: key, title: s.title, intro: s.intro, items: s.items, mode: s.defaultMode, topic: s.topic, saveId: s.id, passage: s.passage || null, script: s.script || null, exam: meta.exam || null });
        render();
      });
      return null;
    }
    // Ready mix: drawn from the mix topics (without items of the last mixed session, when there are enough)
    loadIndex().then(function (index) {
      const mix = index.mixes.find(function (m) { return m.id === route.id; });
      if (!mix) { run = { key: key, missing: true, profileId: profile && profile.id }; return render(); }
      const pick = function () {
        return loadTopicItems(mix.topics).then(function (pool) {
          const res = X().pickMix(playablePool(pool), { count: mix.count || 10, types: mix.types, exclude: pd().lastMix(), weight: LM.stats.mixWeight(pd().attempts()) });
          newRun({
            key: key, title: mix.title, intro: mix.description + (res.items.length < (mix.count || 10) ? " There are only " + LM.plural(res.items.length, "matching item") + " for now." : ""),
            items: res.items, mode: mix.mode, saveId: mix.id, isMix: true
          });
          run.repick = function () { pick().then(function () { begin(); }); };
        });
      };
      pick().then(function () { if (location.hash === hash) render(); });
    });
    return null;
  }

  /**
   * Weak-spot practice: up to 3 topics with ≥ 5 attempts and accuracy < 70% (or one given topic),
   * 12 items, weights: no right answer in the last 14 days × 2.
   */
  function buildWeak(route, key, hash) {
    const profile = LM.app.getActiveProfile();
    const rec = pd().attempts();
    const topics = route.id ? [route.id] : LM.stats.weakTopics(rec).map(function (x) { return x.key; });
    const none = function (text) { run = { key: key, missing: true, missingText: text, missingTitle: "Weak spots", profileId: profile && profile.id }; if (location.hash === hash) render(); };
    if (!topics.length) return none("No weak spots so far. Do a few sets and you will see what to work on.");
    const pick = function () {
      return loadTopicItems(topics).then(function (pool) {
        return X().pickMix(playablePool(pool), { count: 12, weight: LM.stats.weakWeight(pd().attempts(), LM.learn.today()) });
      });
    };
    pick().then(function (res) {
      if (!res.items.length) return none("There are no items for this topic yet.");
      const names = topics.map(function (t) { const i = topicInfo(t); return i ? i.title : t; });
      const launch = function (r, autostart) {
        newRun({
          key: key, title: route.id ? "Practice: " + names[0] : "Weak-spot practice",
          intro: (route.id ? "Items from a topic you find hard. " : "Topics: " + names.join(", ") + ". ") +
            "Items you missed lately come up more often.",
          items: r.items, mode: "learn", isMix: true, isWeak: true,
          repick: function () { pick().then(function (again) { launch(again, true); }); }
        });
        if (autostart) { run.phase = "item"; render(); U.setScroll(0); }
      };
      launch(res, false);
      if (location.hash === hash) render();
    });
  }

  /** A session from the generator (Practice): sets the state and goes to #/practice/session. */
  function startCustom(cfg) {
    newRun(Object.assign({ key: "custom:", isMix: true, title: "Mixed set", saveId: null }, cfg));
    if (cfg.autostart) { run.phase = "item"; run.i = 0; }
    if (location.hash === BASE + "/session") render();
    else location.hash = BASE + "/session";
  }

  /**
   * One item in a review session (js/cards.js, pack v8): a weak-spot item in the engine view
   * (check, explanation, attempts log). cfg: { item, back: { href, label }, progress(), onDone({ correct, skipped }) }.
   * After "Next" the engine hands the result over through onDone and draws no result screen of its own.
   */
  function startSingle(cfg) {
    let reported = false;
    newRun({
      key: "single:", title: cfg.back.label, items: [cfg.item], mode: "learn", isMix: true, isWeak: true, back: cfg.back,
      hooks: {
        progress: cfg.progress, nextLabel: "Next", noJournal: !!cfg.noJournal,
        finish: function (r, s) { return { correct: s.total > 0 && s.score === s.total, skipped: !!(r.items[0].res && r.items[0].res.skipped) }; },
        renderDone: function (view, r) {
          if (reported) return;
          reported = true;
          cfg.onDone(r.final);
        }
      }
    });
    run.phase = "item";
    run.fixedRoute = { kind: "single" };
    render(run.fixedRoute);
    U.setScroll(0);
    focusLater("[data-fk='first']");
  }

  /**
   * Level final test: a session in Exam mode at #/<level>/test. cfg: { level, title, items, hooks, back }
   * hooks: finish(run, { score, total }) → result saved in slm.finals, renderDone(view, run, api),
   * afterFinish(run). No "Retry mistakes only" and no set result in slm.exercises.
   */
  function startFinal(cfg) {
    newRun({ key: "final:" + cfg.level, title: cfg.title, items: cfg.items, mode: "exam", hooks: cfg.hooks, back: cfg.back });
    run.phase = "item";
    run.i = 0;
    if (location.hash !== "#/" + cfg.level.toLowerCase() + "/test") { location.hash = "#/" + cfg.level.toLowerCase() + "/test"; return; }
    render();
    U.setScroll(0);
    focusLater("[data-fk='first']");
  }

  /** Whether item texts and transcripts can be selected (My words): after checking the current item or on the result screen. */
  function textSelectable() {
    if (!run) return false;
    if (run.phase === "done") return true;
    const p = run.items[run.i];
    return run.phase === "item" && !!p && !!p.res;
  }

  /** The item on screen in the current session (or null) — for automated tests. */
  function currentItem() { return run && run.phase === "item" && run.items[run.i] ? run.items[run.i].item : null; }

  /** Engine functions for the result screen of the final test (js/final.js). */
  function api() {
    return {
      head: head, journalSummary: journalSummary, userAnswer: userAnswer, modelAnswer: modelAnswer,
      itemSummary: itemSummary, isWrong: isWrong, typeShort: TYPE_SHORT, repaint: repaint
    };
  }

  function render(route) {
    const view = document.getElementById("view");
    route = route || parseRoute(location.hash) || (run && run.fixedRoute); // a review session (startSingle) runs at #/review/session
    if (!route) return;
    if (route.kind === "hub") return LM.practiceHub.render(route);
    const profile = LM.app.getActiveProfile();
    if (run && profile && run.profileId !== profile.id) run = null; // a profile change = a new session
    view.className = "view tool-view ex-view";
    view.dataset.file = hrefOf(route);
    view.replaceChildren();
    document.title = "Practice · " + LM.APP.appTitle;

    // Level final test: without a started session — the start screen (js/final.js)
    if (route.kind === "final" && (!run || run.key !== "final:" + route.id)) return LM.final.renderStart(view, route.id);

    const ready = ensureRun(route);
    if (ready === false) {
      missing(view, "This session has already ended or the page was reloaded. Draw a new set on the Practice page.");
      return;
    }
    if (ready === null) return view.childNodes.length ? undefined : loading(view); // a synchronous answer may have drawn the view already
    if (run.missing) return missing(view, run.missingText || "This set is not in the exercise bank.", run.missingTitle);
    document.title = run.title + " · " + LM.APP.appTitle;
    if (run.phase === "intro") renderIntro(view);
    else if (run.phase === "item") renderItem(view);
    else renderDone(view);
    const guest = LM.ui.guestNote("your results, mistake log and stats"); // guest mode (spec v7 14, P1)
    if (guest) view.insertBefore(guest, view.firstChild);
  }

  /** Entering from another view: a finished session starts at the start screen. */
  window.addEventListener("hashchange", function () { stopSpeaking(); });

  function onEnter() {
    if (run && run.missing) { run = null; return; } // e.g. weak spots may have appeared by now
    if (!run || run.phase !== "done") return;
    if (/^(mix|weak|final):/.test(run.key)) run = null; // mix / practice / final test: a new draw on the next visit
    else if (!run.isMix) newRun(Object.assign({}, run, { items: run.source, retry: false }));
  }

