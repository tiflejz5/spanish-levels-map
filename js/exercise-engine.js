/*
 * exercise-engine.js — the exercise engine: a set session (Learn / Exam mode),
 * the item types, the result screen, and the "Check yourself" section on topic pages.
 * Specification of the reference app: pack v2 (item types); the types gap-fill, match,
 * transformation, translate, dictation and points: pack v6 (new item types); paradigm ("Fill the table"): spec 06 E6.
 *
 * Routes:
 *   #/practice[/mixes]               Practice (js/practice-hub.js)
 *   #/practice/set/<set id>          a set from content/exercises/
 *   #/practice/mix/<mix id>          a ready mixed set (content/exercises/mixes.json)
 *   #/practice/session               a set drawn in the generator (Practice)
 *   #/practice/weak[/<topic>]        weak-spot practice (spec 03, point 5)
 *
 * Data loads ON DEMAND with a plain <script> (works from file://):
 *   data/sets-index.js     → LM.SETS_INDEX (map, set descriptions, mixes)
 *   data/sets/<id>.js      → LM.EX_SETS[<id>]
 * Generated by tools/build/exercises.js (part of npm run build).
 *
 * Results: LM.profileData (key slm.exercises, per profile).
 * Logic without DOM (scoring, shuffling, drawing mixes): js/exercise-logic.js.
 * Answers typed by the user go into the page only as text.
 */
